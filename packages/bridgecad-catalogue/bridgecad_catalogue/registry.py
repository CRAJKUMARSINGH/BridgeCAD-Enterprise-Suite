def load() -> list[dict]:
    """Return a fresh copy of all 15 booklet cards."""
    return copy.deepcopy(PWD_CARDS)


def by_id(type_id: str) -> dict:
    """Return one card by its booklet drawing number, e.g. ``BR-I-2022-004``."""
    for card in PWD_CARDS:
        if card["id"] == type_id:
            return copy.deepcopy(card)
    raise KeyError(f"unknown booklet type {type_id!r}")
